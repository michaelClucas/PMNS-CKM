"""Neural guidance for the symbolic search (exp 010).

1. Synthetic universes: inputs from the fake-input prior (same as null (b), M_Z real ratios as
   centre), one target observable. Class 1: the target is generated by a planted relation drawn
   from theory-motivated families (Clebsch-scaled CKM angles / sqrt mass ratios, complementarity
   pi/4 +- f, asin/atan of GST-like sums, TBM-anchored corrections, delta = +-dq + k pi/2),
   then NuFIT-sized Gaussian noise. Class 0: target drawn from the Haar-induced distribution,
   independent of the inputs.
2. Network (MLP, torch, 2 threads) maps (inputs, target) features to: P(planted), and
   multi-hot probabilities of which leaves and which ops the generating tree used.
3. Guided search: on a universe, keep the top-4 variable leaves, top-3 constants, top-3 unary
   and top-3 binary ops by network probability and enumerate that restricted grammar exhaustively
   to complexity 7 (brute force over the full grammar stops at 6).
4. Honesty checks: on held-out planted universes, how often is the planted function in
   (i) brute force C <= 6, (ii) the NN-guided C <= 7 set, (iii) a random restriction of the
   same alphabet sizes. On real data: P(planted) for each target vs 300 fakes of each null kind,
   and what the guided set contains that brute force does not.
Outputs: nn_synthetic_eval.json, nn_real.csv, nn_null.csv, nn_guided_top.csv; model in artifacts/.
"""
import csv
import json
import time

import numpy as np
import torch

import pipeline as P
import symlib as S

torch.set_num_threads(2)
CONST_NAMES = [c[0] for c in S.CONSTS]
LIDX = {n: i for i, n in enumerate(S.LEAF_NAMES)}
N_OUT = 1 + S.N_LEAF + 10
KC = ["1/2", "1/3", "2", "3", "sqrt2", "sqrt3"]


# ------------------------------------------------------------------ trees
def L(n):
    return ("L", LIDX[n])


def U(o, x):
    return (o, x)


def B(o, x, y):
    return (o, x, y)


def tree_eval(t, X):
    if t[0] == "L":
        return X[..., t[1]]
    if len(t) == 2:
        return S._apply_unary(t[0], tree_eval(t[1], X))
    return S._apply_binary(t[0], tree_eval(t[1], X), tree_eval(t[2], X))


def tree_feats(t, acc=None):
    acc = acc if acc is not None else (set(), set(), [0])
    acc[2][0] += 1
    if t[0] == "L":
        acc[0].add(t[1])
    else:
        acc[1].add(t[0])
        for c in t[1:]:
            tree_feats(c, acc)
    return acc


def tree_str(t):
    if t[0] == "L":
        return S.LEAF_NAMES[t[1]]
    if len(t) == 2:
        return f"{S.UNARY[t[0]]}({tree_str(t[1])})"
    return f"({tree_str(t[1])} {S.BINARY[t[0]]} {tree_str(t[2])})"


def rand_scaled(rng, x=None):
    x = x or L(rng.choice(S.VAR_LEAVES))
    r = rng.integers(0, 13)
    if r == 0:
        return x
    c = L(KC[(r - 1) % 6])
    return B(9, c, x) if r <= 6 else B(10, x, c)


def planted_tree(rng, target):
    if target == "dcp_deg" and rng.random() < 0.5:
        base = L("dq") if rng.random() < 0.5 else U(1, L("dq"))
        k = rng.integers(0, 4)
        if k == 0:
            return base
        off = [None, L("pi/2"), L("pi"), B(7, L("pi"), L("pi/2"))][k]
        return B(7, base, off)
    f = rng.integers(0, 6)
    pm = 7 if rng.random() < 0.5 else 8
    if f == 0:
        return rand_scaled(rng)
    if f == 1:
        return B(pm, L("pi/4"), rand_scaled(rng))
    if f == 2:
        return U(5 if rng.random() < 0.5 else 6, rand_scaled(rng))
    if f == 3:
        return B(pm, rand_scaled(rng), rand_scaled(rng))
    if f == 4:
        return U(5, B(pm, rand_scaled(rng), rand_scaled(rng)))
    anchor = [U(5, U(2, L("1/3"))), L("pi/4"), U(5, L("1/2"))][rng.integers(0, 3)]
    return B(pm, anchor, rand_scaled(rng))


def valid_angle(v, target):
    if target == "dcp_deg":
        return np.isfinite(v) & (v >= -2 * np.pi) & (v <= 2 * np.pi)
    return np.isfinite(v) & (v >= 0) & (v <= np.pi / 2)


WID = None


def widths():
    global WID
    if WID is None:
        WID = S._sig_max()
    return WID


def obs_from_angle(v, target, rng):
    """true angle -> noisy observed target value (s^2 or delta deg)."""
    w = widths()[target]
    if target == "dcp_deg":
        return np.mod(np.degrees(v) + rng.normal(0, w, np.shape(v)), 360)
    return np.clip(np.sin(v) ** 2 + rng.normal(0, w, np.shape(v)), 1e-6, 1 - 1e-6)


def haar_obs(rng, n, target):
    from src.haar import sample_haar_angles
    t12, t13, t23, d = sample_haar_angles(rng, n)
    return {"s12sq": np.sin(t12) ** 2, "s13sq": np.sin(t13) ** 2, "s23sq": np.sin(t23) ** 2,
            "dcp_deg": np.degrees(d)}[target]


def features(base, target_idx, obs):
    """base (n,10), target_idx (n,), obs (n,) -> (n, F)."""
    base = np.asarray(base, float)
    n = len(base)
    X = S.leaf_values(base)[:, :S.N_VAR]  # 16 var leaves
    lx = np.log(np.abs(X) + 1e-12)
    is_d = target_idx == 3
    th = np.where(is_d, 0.0, np.arcsin(np.sqrt(np.clip(np.where(is_d, 0.5, obs), 0, 1))))
    dr = np.radians(np.where(is_d, obs, 0.0))
    lt = np.log(th + 1e-6)
    lc = np.log(np.abs(np.pi / 4 - th) + 1e-6)
    oh = np.eye(4)[target_idx]
    f = [lx[:, :3], np.cos(base[:, 3:4]), np.sin(base[:, 3:4]), lx[:, 4:10], oh,
         th[:, None], lt[:, None], np.where(is_d, 0, np.sin(th) ** 2)[:, None],
         np.where(is_d, np.cos(dr), 0)[:, None], np.where(is_d, np.sin(dr), 0)[:, None],
         np.where(is_d[:, None], 0, lt[:, None] - lx), np.where(is_d[:, None], 0, lc[:, None] - lx),
         np.where(is_d[:, None], np.cos(dr[:, None] - base[:, 3:4]), 0),
         np.where(is_d[:, None], np.cos(dr[:, None] + base[:, 3:4]), 0)]
    return np.concatenate(f, axis=1).astype(np.float32)


def make_dataset(rng, n, real_ratios, keep_trees=False):
    base = S.fake_base_inputs(rng, real_ratios, n)
    Xl = S.leaf_values(base)
    tgt = rng.integers(0, 4, n)
    cls = (rng.random(n) < 0.5).astype(np.float32)
    obs = np.empty(n)
    Y = np.zeros((n, N_OUT - 1), np.float32)
    trees = [None] * n
    comp = np.zeros(n, int)
    for i in range(n):
        tn = S.TARGETS[tgt[i]]
        if cls[i]:
            for _ in range(50):
                t = planted_tree(rng, tn)
                v = tree_eval(t, Xl[i])
                if valid_angle(v, tn):
                    break
            else:
                cls[i] = 0
        if cls[i]:
            obs[i] = obs_from_angle(v, tn, rng)
            lv, ops, c = tree_feats(t)
            Y[i, list(lv)] = 1
            Y[i, [S.N_LEAF + o - 1 for o in ops]] = 1
            comp[i] = c[0]
            if keep_trees:
                trees[i] = t
        else:
            obs[i] = haar_obs(rng, 1, tn)[0]
    return base, tgt, obs, cls, Y, trees, comp


class Net(torch.nn.Module):
    def __init__(self, F):
        super().__init__()
        self.mu = torch.nn.Parameter(torch.zeros(F), requires_grad=False)
        self.sd = torch.nn.Parameter(torch.ones(F), requires_grad=False)
        self.f = torch.nn.Sequential(torch.nn.Linear(F, 256), torch.nn.SiLU(), torch.nn.Linear(256, 256),
                                     torch.nn.SiLU(), torch.nn.Linear(256, 256), torch.nn.SiLU(),
                                     torch.nn.Linear(256, N_OUT))

    def forward(self, x):
        return self.f((x - self.mu) / self.sd)


def train(Xf, cls, Y, epochs=12, log=print):
    torch.manual_seed(0)
    net = Net(Xf.shape[1])
    Xt = torch.tensor(Xf)
    net.mu.data = Xt.mean(0)
    net.sd.data = Xt.std(0) + 1e-6
    ct, Yt = torch.tensor(cls), torch.tensor(Y)
    opt = torch.optim.Adam(net.parameters(), 2e-3)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
    bce = torch.nn.functional.binary_cross_entropy_with_logits
    n = len(Xt)
    for ep in range(epochs):
        perm = torch.randperm(n)
        tot = 0.0
        for s in range(0, n, 1024):
            idx = perm[s:s + 1024]
            out = net(Xt[idx])
            l1 = bce(out[:, 0], ct[idx])
            m = ct[idx] > 0
            l2 = bce(out[m, 1:], Yt[idx][m]) if m.any() else 0
            loss = l1 + l2
            opt.zero_grad(); loss.backward(); opt.step()
            tot += float(loss) * len(idx)
        sched.step()
        log(f"[nn] epoch {ep} loss {tot / n:.4f}")
    return net


def predict(net, Xf):
    with torch.no_grad():
        return torch.sigmoid(net(torch.tensor(Xf))).numpy()


def alphabet(prob_row, rng=None, nv=4, nc=3, nu=3, nb=3):
    pl = prob_row[1:1 + S.N_LEAF]
    po = prob_row[1 + S.N_LEAF:]
    if rng is None:
        v = np.argsort(-pl[:S.N_VAR])[:nv]
        c = S.N_VAR + np.argsort(-pl[S.N_VAR:])[:nc]
        u = 1 + np.argsort(-po[:6])[:nu]
        b = 7 + np.argsort(-po[6:])[:nb]
    else:
        v = rng.choice(S.N_VAR, nv, replace=False)
        c = S.N_VAR + rng.choice(len(S.CONSTS), nc, replace=False)
        u = 1 + rng.choice(6, nu, replace=False)
        b = 7 + rng.choice(4, nb, replace=False)
    return sorted(np.concatenate([v, c]).tolist()), sorted(u.tolist()), sorted(b.tolist())


def enum_hashes(op, a, b, comp):
    fp = S.default_fp_base()
    V = np.stack([S.evaluate(op, a, b, comp, x)[0] for x in fp], axis=1)
    return S._hash_rows(V)


def tree_hash(t):
    fp = S.default_fp_base()
    X = S.leaf_values(fp)
    return S._hash_rows(tree_eval(t, X)[None, :])[0]


GUIDED_C = 7
import sys
N_TRAIN = int(sys.argv[1]) if len(sys.argv) > 1 else 300_000
N_DEEP = int(sys.argv[2]) if len(sys.argv) > 2 else 60
EPOCHS = int(sys.argv[3]) if len(sys.argv) > 3 else 12
OUT_SUFFIX = "" if len(sys.argv) <= 4 else sys.argv[4]


def main():
    t0 = time.time()
    logf = open(S.HERE / "run.log", "a")

    def log(m):
        print(m, flush=True)
        logf.write(m + "\n"); logf.flush()

    real_mz = S.real_inputs("MZ")
    rr = real_mz["base"][4:]
    rng = np.random.default_rng(31337)
    base, tgt, obs, cls, Y, _, _ = make_dataset(rng, N_TRAIN, rr)
    Xf = features(base, tgt, obs)
    log(f"[nn] synthetic train set {len(Xf)} rows, {Xf.shape[1]} features, {time.time() - t0:.0f}s")
    net = train(Xf, cls, Y, epochs=EPOCHS, log=log)
    S.ART.mkdir(parents=True, exist_ok=True)
    torch.save(net.state_dict(), S.ART / "nn_guide.pt")

    # ---- held-out synthetic evaluation
    rng_t = np.random.default_rng(4242)
    bt, tt, ot, ct, Yt, trees, compt = make_dataset(rng_t, min(20_000, N_TRAIN), rr, keep_trees=True)
    pr = predict(net, features(bt, tt, ot))
    from scipy.stats import rankdata
    ev = {}
    rk = rankdata(pr[:, 0])
    n1, n0 = int(ct.sum()), int((1 - ct).sum())
    ev["auc_planted_vs_haar"] = float((rk[ct > 0].sum() - n1 * (n1 + 1) / 2) / (n1 * n0))
    m = ct > 0
    leaf_rank_ok = []
    for i in np.nonzero(m)[0][:3000]:
        true_vars = set(np.nonzero(Yt[i, :S.N_VAR])[0])
        top = set(np.argsort(-pr[i, 1:1 + S.N_VAR])[:4])
        leaf_rank_ok.append(true_vars <= top)
    ev["frac_true_var_leaves_in_top4"] = float(np.mean(leaf_rank_ok))
    log(f"[nn] held-out: {ev}")

    # recovery of planted functions with complexity >= 5
    Eb = S.Loaded(S.ART / "enum_C6.npz")
    hb = np.sort(enum_hashes(Eb.op, Eb.a, Eb.b, Eb.comp))
    deep = [i for i in np.nonzero(m)[0] if compt[i] >= 5][:N_DEEP]
    rec = {"brute_C6": 0, "nn_guided_C7": 0, "random_alphabet_C7": 0}
    sizes = {"nn": [], "rand": []}
    rr_rng = np.random.default_rng(777)
    by_c = {}
    for k, i in enumerate(deep):
        h = tree_hash(trees[i])
        inb = bool(np.isin(h, hb))
        rec["brute_C6"] += inb
        ls, us, bs = alphabet(pr[i])
        Eg = S.Enum(GUIDED_C, ls, us, bs)
        hg = enum_hashes(Eg.op, Eg.a, Eg.b, Eg.comp)
        ing = bool(np.isin(h, hg))
        rec["nn_guided_C7"] += ing
        sizes["nn"].append(len(Eg))
        ls, us, bs = alphabet(pr[i], rr_rng)
        Er = S.Enum(GUIDED_C, ls, us, bs)
        inr = bool(np.isin(h, enum_hashes(Er.op, Er.a, Er.b, Er.comp)))
        rec["random_alphabet_C7"] += inr
        sizes["rand"].append(len(Er))
        c = int(compt[i])
        d = by_c.setdefault(c, [0, 0, 0, 0])
        d[0] += 1; d[1] += inb; d[2] += ing; d[3] += inr
        if k % 20 == 0:
            log(f"[nn] recovery {k}/{len(deep)} {rec} {time.time() - t0:.0f}s")
    ev["recovery_n"] = len(deep)
    ev["recovery"] = rec
    ev["recovery_by_planted_complexity"] = {str(c): dict(zip(["n", "brute_C6", "nn_C7", "random_C7"], v))
                                             for c, v in sorted(by_c.items())}
    ev["guided_set_size_median"] = {k: float(np.median(v)) for k, v in sizes.items()}
    ev["brute_set_size"] = len(Eb)
    log(f"[nn] recovery: {ev['recovery']} by C {ev['recovery_by_planted_complexity']} sizes {ev['guided_set_size_median']}")

    # ---- real data and nulls for the NN statistic P(planted)
    from src import data
    rows_real, rows_null, top_rows = [], [], []
    for scale in ("MZ", "GUT"):
        real = S.real_inputs(scale)
        for o in P.ORDERINGS:
            pm = data.load_pmns(o)
            for ti, tn in enumerate(S.TARGETS):
                f = features(real["base"][None], np.array([ti]), np.array([pm[tn]["value"]]))
                prr = predict(net, f)[0]
                # null (a): real inputs, Haar target; null (b): fake inputs, real target
                rng_a = np.random.default_rng([5001, ti])
                oa = haar_obs(rng_a, 300, tn)
                pa = predict(net, features(np.repeat(real["base"][None], 300, 0), np.full(300, ti), oa))[:, 0]
                rng_b = np.random.default_rng([5002 if scale == "MZ" else 5003, ti])
                bb = S.fake_base_inputs(rng_b, real["base"][4:], 300)
                pb = predict(net, features(bb, np.full(300, ti), np.full(300, pm[tn]["value"])))[:, 0]
                ha, hb_ = int((pa >= prr[0]).sum()), int((pb >= prr[0]).sum())
                ra, rb = S_rate(ha, 300), S_rate(hb_, 300)
                ls, us, bs = alphabet(prr)
                rows_real.append([scale, o, tn, float(prr[0]), " ".join(S.LEAF_NAMES[x] for x in ls),
                                  " ".join(S.OPNAMES[x] for x in us + bs)])
                rows_null.append([scale, o, tn, float(prr[0]), ha, 300, ra["rate"], ra["lo"], ra["hi"],
                                  hb_, 300, rb["rate"], rb["lo"], rb["hi"]])
                # guided deep search on real data
                Eg = S.Enum(GUIDED_C, ls, us, bs)
                hg = enum_hashes(Eg.op, Eg.a, Eg.b, Eg.comp)
                new = ~np.isin(hg, hb)
                v, T = Eg.evaluate(real["base"], real["dirs"])
                p, s = S.predictions(v, T, tn)
                pull = P.profile_scorer(tn, o).pull(p, s)
                ap = np.where(np.isfinite(pull), np.abs(pull), np.inf)
                n_new = int(new.sum())
                n_new_lt1 = int((new & (ap < 1)).sum())
                best_new = float(ap[new].min()) if n_new else np.inf
                best_new_c = int(Eg.comp[new][np.argmin(ap[new])]) if n_new else -1
                order = np.argsort(np.where(new, ap, np.inf))[:5]
                for j in order:
                    top_rows.append([scale, o, tn, len(Eg), n_new, n_new_lt1, int(Eg.comp[j]), Eg.expr(j),
                                     float(p[j]), float(s[j]), float(pull[j])])
                log(f"[nn] real {scale} {o} {tn}: P(planted)={prr[0]:.3f} null a {ha}/300 b {hb_}/300; "
                    f"guided {len(Eg)} exprs, {n_new} not in brute C<=6, {n_new_lt1} of those |pull|<1, "
                    f"best new |pull| {best_new:.3g} at C{best_new_c}")
    with open(S.HERE / f"nn_real{OUT_SUFFIX}.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["scale", "ordering", "target", "P_planted", "guided_leaves", "guided_ops"])
        w.writerows(rows_real)
    with open(S.HERE / f"nn_null{OUT_SUFFIX}.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["scale", "ordering", "target", "P_planted_real", "hits_a", "n_a", "rate_a", "lo_a", "hi_a",
                    "hits_b", "n_b", "rate_b", "lo_b", "hi_b"])
        w.writerows(rows_null)
    with open(S.HERE / f"nn_guided_top{OUT_SUFFIX}.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["scale", "ordering", "target", "guided_size", "n_not_in_brute", "n_not_in_brute_lt1",
                    "complexity", "expression", "prediction", "sigma_pred", "pull"])
        w.writerows(top_rows)
    (S.HERE / f"nn_synthetic_eval{OUT_SUFFIX}.json").write_text(json.dumps(ev, indent=1))
    log(f"[nn] done {time.time() - t0:.0f}s")


def S_rate(k, n):
    from src.stats import fake_universe_rate
    return fake_universe_rate(k, n)


if __name__ == "__main__":
    main()
